"""`seo.py client <slug> <domain>`: a client profile from the live site, for any kind of website.

Reads the homepage (and the sitemap index if there is one) to fill in what the site itself states: its name,
platform, language/region, and where its articles live. Everything that needs a human (approved claims, client
facts, niche synonyms, banned phrases) starts empty with a comment saying what goes there; the pipeline runs
without them and treats the client conservatively (no claims about the business).
"""
from __future__ import annotations

import re
from pathlib import Path

import yaml

from . import common as C


def _get(url: str, parse: str = "html") -> dict:
    return C.run_async(C.fetch_many([{"url": url, "kind": "page", "parse": parse}], timeout=12, attempts=2)).get(url) or {}


def onboard(slug: str, domain: str, force: bool = False) -> Path:
    domain = re.sub(r"^https?://", "", domain).strip("/").removeprefix("www.")
    out = C.ROOT / "clients" / f"{slug}.yaml"
    out.parent.mkdir(parents=True, exist_ok=True)
    if out.exists() and not force:
        raise SystemExit(f"{out} exists (use --force to overwrite)")
    home = _get(f"https://{domain}/", "raw") or {}
    html = home.get("raw") or ""
    if not html:
        raise SystemExit(f"Could not read https://{domain}/ ({home.get('state')} {home.get('status')}); "
                         "write the profile by hand from clients/house-of-velorien.yaml")
    title = re.search(r"<title[^>]*>(.*?)</title>", html, re.I | re.S)
    site_name = re.search(r'property=["\']og:site_name["\'][^>]*content=["\']([^"\']+)', html, re.I)
    org = re.search(r'"@type"\s*:\s*"(?:Organization|Corporation|LocalBusiness|Store|OnlineStore)"[^{}]*?"name"\s*:\s*"([^"]+)"', html) or         re.search(r'"name"\s*:\s*"([^"]+)"[^{}]*?"@type"\s*:\s*"(?:Organization|Corporation|LocalBusiness|Store|OnlineStore)"', html)
    root = domain.split(".")[0]
    cands = [m.group(1).strip() for m in (site_name, org) if m]
    if title:
        # titles are "Brand | tagline" or "tagline | Brand": take the part that matches the domain
        parts = [x.strip() for x in re.split(r"\s[|\-–—:]\s", title.group(1)) if x.strip()]
        cands += sorted(parts, key=lambda x: re.sub(r"[^a-z0-9]", "", x.lower()) != root)
    name = next((c for c in cands if re.sub(r"[^a-z0-9]", "", c.lower()).startswith(root[:4])), None) or         (cands[0] if cands and len(cands[0].split()) <= 3 else root.replace("-", " ").title())
    lang = re.search(r"<html[^>]*\blang=[\"']([a-zA-Z-]+)", html)
    locale = lang.group(1) if lang else ("en-GB" if domain.endswith(".uk") else "en-US")
    # many UK sites ship lang="en-US" from their theme: trust what the page sells and how it gives its phone number
    uk = (domain.endswith(".uk") or html.count("£") >= 2 or len(re.findall(r"\+44|\b0(?:800|330|345|20)\s?\d", html)) >= 1
          or len(re.findall(r"\bUK\b|United Kingdom", html)) >= 3)
    if "-" not in locale or (locale.lower() == "en-us" and uk):
        locale = "en-GB" if locale.lower().startswith("en") and uk else ("en-US" if locale.lower().startswith("en") else locale)
    lp = locale.split("-")
    locale = lp[0].lower() + ("-" + lp[1].upper() if len(lp) > 1 else "")
    platform = ("shopify" if re.search(r"cdn\.shopify\.com|Shopify\.theme", html) else
                "wordpress" if re.search(r"wp-content|wp-includes", html) else
                "wix" if "wix.com" in html else "squarespace" if "squarespace" in html else "other")
    blog_path = "/blogs/news/" if platform == "shopify" else "/blog/"
    for cand in ("/blogs/news/", "/blogs/blog/", "/blog/", "/news/", "/articles/", "/guides/", "/learn/"):
        if re.search(rf'href=["\'](https?://[^"\']*)?{re.escape(cand)}', html):
            blog_path = cand
            break
    prof = {
        "client": name,
        "client_aliases": [],
        "domain": domain,
        "locale": locale,
        "platform": platform,
        "hardcode_prices": False,
        "ymyl": "auto",
        "client_facts": [],
        "approved_claims": [],
        "banned_claims": ["guarantee", "guaranteed"],
        "banned_phrases": [],
        "proper_nouns": [name],
        "reader_nouns": [],
        "synonyms": {},
        "blog_path": blog_path,
        # E-E-A-T inputs only a person can give: a real reviewer for the byline, and genuine first-hand notes
        "author": "",
        "experience": [],
    }
    if platform == "shopify":
        prof["default_product_sources"] = {"collection": "all"}
    header = (f"# Client profile for {domain}, generated by `seo.py client {slug} {domain}`.\n"
              "# Filled from the live site. Add what only the client can confirm:\n"
              "#   client_facts: who they are (otherwise the copy never describes the business)\n"
              "#   approved_claims: service claims, each must also appear on the site\n"
              "#   synonyms / reader_nouns / banned_phrases: niche vocabulary and words to avoid\n")
    out.write_text(header + yaml.safe_dump(prof, sort_keys=False, allow_unicode=True), encoding="utf-8")
    print(f"CLIENT {out.relative_to(C.ROOT).as_posix()}  ({name}; {platform}; {locale}; blog {blog_path})")
    return out
