"""`seo.py brief <client> "<query>"`: a full brief from a client profile in clients/.

Client-level facts, claims, bans and voice live in clients/<client>.yaml; the
page-level fields come from flags with sensible defaults per page type. Intent
is left to the SERP (`search_intent: auto`) and official facts to the
official_facts plugin, so a new page needs only a query.
"""
from __future__ import annotations

from pathlib import Path

import yaml

from . import common as C

WORDS = {"guide": [1000, 1600], "hub": [600, 900], "spoke": [800, 1300], "product-guide": [900, 1500],
         "service": [800, 1400], "location": [700, 1200], "product": [400, 900], "category": [300, 700],
         "home": [500, 1000], "company": [400, 800]}


def default_page_url(profile: dict, page_type: str, slug: str) -> str:
    domain = profile["domain"]
    paths = {"guide": profile.get("blog_path", "/blog/"), "spoke": profile.get("blog_path", "/blog/"),
             "product-guide": profile.get("blog_path", "/blog/"), "product": "/products/",
             "category": "/collections/" if profile.get("platform") == "shopify" else "/categories/"}
    paths.update(profile.get("page_paths") or {})
    return f"https://{domain}/" if page_type == "home" else (
        f"https://{domain}{paths.get(page_type, '/').rstrip('/')}/{slug}")


def set_page_type(brief: dict, page_type: str, source: str, profile: dict | None = None) -> None:
    """Change inferred defaults together; preserve the operator's URL and length choices."""
    changed = brief.get("page_type") != page_type
    brief.update(page_type=page_type, page_type_source=source)
    if not changed:
        return
    brief.pop("word_range_effective", None)
    if brief.get("word_range_source") == "type":
        brief["word_range"] = WORDS[page_type]
    if brief.get("page_url_source") == "generated" and brief.get("task") != "rewrite":
        from urllib.parse import urlparse
        slug = urlparse(brief.get("page_url") or "").path.rstrip("/").rsplit("/", 1)[-1]
        if brief.get("domain"):
            brief["page_url"] = default_page_url(profile or brief, page_type, slug or C.slugify(brief["target_query"]))


def make_brief(client: str, query: str, url: str | None = None, page_type: str | None = None,
               words: list[int] | None = None, task: str = "new", checks: list[str] | None = None,
               slug: str | None = None, ymyl: bool | None = None, instructions: str | None = None,
               page_type_source: str | None = None) -> Path:
    prof_path = C.ROOT / "clients" / f"{client}.yaml"
    if not prof_path.exists():
        raise SystemExit(f"No client profile {prof_path}. Available: " +
                         ", ".join(p.stem for p in (C.ROOT / "clients").glob("*.yaml")))
    prof = C.load_yaml(prof_path)
    from .pagetype import explicit_type, infer_type
    if page_type is None:
        page_type, _ = infer_type(instructions or "", query)
        page_type_source = "explicit" if explicit_type(instructions or "") else "keyword"
    slug = slug or C.slugify(query)
    proposed = default_page_url(prof, page_type, slug)
    b = {k: v for k, v in prof.items() if k not in ("default_product_sources", "blog_path")}
    b.update({
        "page_url": url or proposed, "page_url_source": "explicit" if url else "generated",
        "page_type": page_type, "target_query": query, "search_intent": "auto",
        "page_type_source": page_type_source or "explicit", "word_range_source": "explicit" if words else "type",
        "word_range": words or WORDS.get(page_type, [900, 1400]), "task": task, "mode": "auto",
        "connectors": "auto",
    })
    if ymyl is not None:
        b["ymyl"] = ymyl
    if instructions:
        b["instructions"] = instructions  # the operator's own words for this page, shown to every role
    if prof.get("platform") == "shopify" and page_type in ("guide", "product-guide") and prof.get("default_product_sources"):
        b["product_sources"] = prof["default_product_sources"]
    if checks:
        b["vertical_checks"] = checks
    out = C.ROOT / "briefs" / f"{slug}.yaml"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(f"# Generated by `seo.py brief {client} \"{query}\"`. Edit freely.\n"
                   + yaml.safe_dump(b, sort_keys=False, allow_unicode=True), encoding="utf-8")
    print(f"BRIEF {out.relative_to(C.ROOT).as_posix()}  ({page_type}, {b['page_url']})")
    return out
